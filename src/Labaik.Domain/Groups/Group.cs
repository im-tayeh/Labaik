using Labaik.Domain.Announcements;
using Labaik.Domain.Chat;
using Labaik.Domain.Common;
using Labaik.Domain.Common.Results;
using Labaik.Domain.Groups.Enums;
using Labaik.Domain.Groups.Events;
using Labaik.Domain.Groups.ValueObjects;

namespace Labaik.Domain.Groups;

public sealed class Group : AggregateRoot
{
    public string Name { get; private set; } = string.Empty;
    public string JoinCode { get; private set; } = string.Empty;

    // Null until a supervisor is assigned (company-managed groups start without one).
    public Guid? LeaderId { get; private set; }

    // Set for company-managed groups; null for legacy self-created groups.
    public Guid? CompanyId { get; private set; }
    public Guid? TripId { get; private set; }

    private readonly List<GroupMember> _members = [];
    public IReadOnlyList<GroupMember> Members => _members.AsReadOnly();

    // Null until the supervisor sets one.
    public GatheringPoint? GatheringPoint { get; private set; }

    public int MemberCount => _members.Count;
    public int PilgrimCount => _members.Count(m => m.Role == GroupMemberRole.Member);
    public bool HasSupervisor => LeaderId is not null;

    private Group() { } // EF

    private Group(string name, string joinCode, Guid? leaderId, Guid? companyId, Guid? tripId, DateTimeOffset createdAtUtc)
    {
        Name = name;
        JoinCode = joinCode;
        LeaderId = leaderId;
        CompanyId = companyId;
        TripId = tripId;

        if (leaderId is { } leader)
        {
            // The leader is the first member.
            _members.Add(new GroupMember(leader, GroupMemberRole.Leader, createdAtUtc));
        }

        Raise(new GroupCreated(Id, leaderId, companyId, tripId));
    }

    // Factory (legacy/admin): joinCode is supplied by the app layer (generated by an infrastructure service).
    public static Result<Group> Create(string name, string joinCode, Guid leaderId, DateTimeOffset createdAtUtc)
    {
        var valid = Validate(name, joinCode);
        if (valid.IsFailure)
        {
            return valid.Error!;
        }

        if (leaderId == Guid.Empty)
        {
            return GroupErrors.LeaderRequired;
        }

        return new Group(name.Trim(), joinCode.Trim().ToUpperInvariant(), leaderId, null, null, createdAtUtc);
    }

    // Factory (company-managed): created under a company's trip, without a supervisor yet.
    public static Result<Group> CreateForTrip(
        string name, string joinCode, Guid companyId, Guid tripId, DateTimeOffset createdAtUtc)
    {
        var valid = Validate(name, joinCode);
        if (valid.IsFailure)
        {
            return valid.Error!;
        }

        if (companyId == Guid.Empty || tripId == Guid.Empty)
        {
            return GroupErrors.TripRequired;
        }

        return new Group(name.Trim(), joinCode.Trim().ToUpperInvariant(), null, companyId, tripId, createdAtUtc);
    }

    private static Result Validate(string name, string joinCode)
    {
        if (string.IsNullOrWhiteSpace(name))
        {
            return Result.Failure(GroupErrors.NameRequired);
        }

        if (name.Trim().Length > GroupErrors.NameMaxLength)
        {
            return Result.Failure(GroupErrors.NameTooLong);
        }

        return string.IsNullOrWhiteSpace(joinCode) ? Result.Failure(GroupErrors.JoinCodeRequired) : Result.Success();
    }

    public bool IsMember(Guid userId) => _members.Any(m => m.UserId == userId);

    // Makes userId the group's supervisor. A previous supervisor (staff, not a pilgrim) leaves the group;
    // an existing member is promoted, anyone else is added as leader.
    public Result AssignSupervisor(Guid userId, DateTimeOffset assignedAtUtc)
    {
        if (userId == Guid.Empty)
        {
            return Result.Failure(GroupErrors.LeaderRequired);
        }

        if (LeaderId == userId)
        {
            return Result.Success(); // idempotent
        }

        if (LeaderId is { } previous)
        {
            _members.RemoveAll(m => m.UserId == previous);
        }

        var existing = _members.FirstOrDefault(m => m.UserId == userId);
        if (existing is not null)
        {
            existing.PromoteToLeader();
        }
        else
        {
            _members.Add(new GroupMember(userId, GroupMemberRole.Leader, assignedAtUtc));
        }

        LeaderId = userId;
        Raise(new SupervisorAssigned(Id, userId, CompanyId));
        return Result.Success();
    }

    // Company adds a pilgrim (same rules and event as joining by code).
    public Result AddMember(Guid userId, DateTimeOffset addedAtUtc) => Join(userId, addedAtUtc);

    public Result RemoveMember(Guid userId)
    {
        var member = _members.FirstOrDefault(m => m.UserId == userId);
        if (member is null)
        {
            return Result.Failure(GroupErrors.MemberNotFound);
        }

        if (member.Role == GroupMemberRole.Leader)
        {
            return Result.Failure(GroupErrors.CannotRemoveSupervisor);
        }

        _members.Remove(member);
        return Result.Success();
    }

    // Only the supervisor sets where the group gathers; members are notified.
    public Result SetGatheringPoint(
        Guid byUserId, string address, double latitude, double longitude, DateTimeOffset? gatheringTimeUtc, DateTimeOffset nowUtc)
    {
        if (LeaderId != byUserId)
        {
            return Result.Failure(GroupErrors.NotLeader);
        }

        if (string.IsNullOrWhiteSpace(address))
        {
            return Result.Failure(GroupErrors.AddressRequired);
        }

        address = address.Trim();
        if (address.Length > GatheringPoint.AddressMaxLength)
        {
            return Result.Failure(GroupErrors.AddressTooLong);
        }

        if (latitude is < -90 or > 90 || longitude is < -180 or > 180 || double.IsNaN(latitude) || double.IsNaN(longitude))
        {
            return Result.Failure(GroupErrors.InvalidCoordinates);
        }

        GatheringPoint = new GatheringPoint(address, latitude, longitude, gatheringTimeUtc, nowUtc);
        Raise(new GatheringPointChanged(Id, byUserId));
        return Result.Success();
    }

    // A pilgrim's "I arrived". Idempotent: confirming again changes nothing and notifies no one.
    public Result ConfirmArrival(Guid userId, DateTimeOffset nowUtc)
    {
        var member = _members.FirstOrDefault(m => m.UserId == userId);
        if (member is null)
        {
            return Result.Failure(GroupErrors.MemberNotFound);
        }

        if (member.Role != GroupMemberRole.Member)
        {
            return Result.Failure(GroupErrors.NotPilgrim);
        }

        if (member.AttendanceStatus == AttendanceStatus.Present)
        {
            return Result.Success();
        }

        member.SetAttendance(AttendanceStatus.Present, nowUtc);
        Raise(new PilgrimArrived(Id, userId));
        return Result.Success();
    }

    // Supervisor marks a pilgrim present or absent manually.
    public Result SetAttendance(Guid byUserId, Guid pilgrimId, AttendanceStatus status, DateTimeOffset nowUtc)
    {
        if (LeaderId != byUserId)
        {
            return Result.Failure(GroupErrors.NotLeader);
        }

        if (!Enum.IsDefined(status))
        {
            return Result.Failure(GroupErrors.InvalidAttendanceStatus);
        }

        var member = _members.FirstOrDefault(m => m.UserId == pilgrimId && m.Role == GroupMemberRole.Member);
        if (member is null)
        {
            return Result.Failure(GroupErrors.MemberNotFound);
        }

        member.SetAttendance(status, nowUtc);
        return Result.Success();
    }

    // Supervisor starts a new roll call: every pilgrim back to Absent.
    public Result ResetAttendance(Guid byUserId)
    {
        if (LeaderId != byUserId)
        {
            return Result.Failure(GroupErrors.NotLeader);
        }

        foreach (var member in _members.Where(m => m.Role == GroupMemberRole.Member))
        {
            member.SetAttendance(AttendanceStatus.Absent, default);
        }

        return Result.Success();
    }

    // Only the leader broadcasts to the group. The new Announcement is its own aggregate;
    // this group is not modified.
    public Result<Announcement> PostAnnouncement(Guid authorId, string title, string body, DateTimeOffset postedAtUtc)
    {
        if (LeaderId != authorId)
        {
            return GroupErrors.NotLeader;
        }

        return Announcement.Create(Id, authorId, title, body, postedAtUtc);
    }

    // Any member may chat in the group. The new ChatMessage is its own aggregate; this group is not modified.
    public Result<ChatMessage> PostMessage(Guid senderId, string body, DateTimeOffset sentAtUtc)
    {
        if (!IsMember(senderId))
        {
            return ChatErrors.NotMember;
        }

        return ChatMessage.Create(Id, senderId, body, sentAtUtc);
    }

    public Result Join(Guid userId, DateTimeOffset joinedAtUtc)
    {
        if (_members.Any(m => m.UserId == userId))
        {
            return Result.Failure(GroupErrors.AlreadyMember);
        }

        _members.Add(new GroupMember(userId, GroupMemberRole.Member, joinedAtUtc));
        Raise(new MemberJoinedGroup(Id, userId));

        // Pilgrims are now waiting in a company group with nobody responsible: tell the company once.
        if (CompanyId is { } companyId && !HasSupervisor && PilgrimCount == 1)
        {
            Raise(new GroupAwaitingSupervisor(Id, companyId));
        }

        return Result.Success();
    }
}
